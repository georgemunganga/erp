internal sealed record WorkspaceCompanyPreferences(string CountryCode, string Currency, string TimeZoneId)
{
    internal static readonly WorkspaceCompanyPreferences Zambia = new("ZM", "ZMW", "Africa/Lusaka");
    internal bool Valid => Regex.IsMatch(CountryCode, "^[A-Z]{2}\\z") && Regex.IsMatch(Currency, "^[A-Z]{3}\\z")
        && TimeZoneId.Length is > 0 and <= 100 && TimeZoneInfo.TryFindSystemTimeZoneById(TimeZoneId, out _);
}

internal enum WorkspaceCreateStatus { Created, Existing, Invalid, Denied, CapacityExhausted, Conflict, Unavailable }
internal sealed record WorkspaceCreateResult(WorkspaceCreateStatus Status, Guid? CompanyId = null, Guid? BindingId = null);

/// <summary>Explicit Core-owned transaction; caller must hold a protected setup grant. No public endpoint.</summary>
internal sealed class CoreWorkspaceProvisioner(Func<string, HrmDbContext> contextFactory, TimeProvider clock)
{
    internal async Task<WorkspaceCreateResult> CreateAsync(WorkspaceSetupObservation authority, CommercialLicenseLease license,
        string idempotencyKey, string companyName, CancellationToken cancellation = default)
        => await CreateAsync(authority, license, idempotencyKey, companyName, WorkspaceCompanyPreferences.Zambia, cancellation);

    internal async Task<WorkspaceCreateResult> CreateAsync(WorkspaceSetupObservation authority, CommercialLicenseLease license,
        string idempotencyKey, string companyName, WorkspaceCompanyPreferences preferences, CancellationToken cancellation = default)
    {
        if (!preferences.Valid) return new(WorkspaceCreateStatus.Invalid);
        if (!Regex.IsMatch(idempotencyKey, "^[A-Za-z0-9_-]{32,128}\\z", RegexOptions.CultureInvariant)
            || companyName.Length is < 1 or > 200 || companyName.Any(char.IsControl)
            || string.IsNullOrWhiteSpace(companyName)) return new(WorkspaceCreateStatus.Invalid);
        string name;
        try { name = companyName.Trim().Normalize(NormalizationForm.FormC); }
        catch (ArgumentException) { return new(WorkspaceCreateStatus.Invalid); }
        if (name.Length is < 1 or > 200) return new(WorkspaceCreateStatus.Invalid);
        bool Current() => authority.IsCurrent && license.IsCurrent && authority.EnrollmentId == license.EnrollmentId
            && authority.WorkspaceLimit == license.WorkspaceLimit && authority.WorkspaceLimit is > 0 and <= 10000;
        if (!Current()) return new(WorkspaceCreateStatus.Denied);
        var keyHash = Hash(idempotencyKey);
        // All references are canonical, and the name excludes control characters;
        // fixed line framing keeps retry hashes stable across JSON encoder updates.
        var requestHash = Hash(string.Join('\n', "core.workspace.create.v1", authority.Subject, authority.ClientId,
            authority.CustomerId, authority.EnrollmentId, name, preferences.CountryCode, preferences.Currency, preferences.TimeZoneId));
        // New trusted scope is generated by Core; never use request tenant headers/default tenant.
        var tenant = Guid.CreateVersion7().ToString("D");
        await using var db = contextFactory(tenant);
        try
        {
            // PostgreSQL takes a new read snapshot after acquiring the advisory
            // lock, so a waiting creator sees the previous committed allocation.
            await using var transaction = await db.Database.BeginTransactionAsync(
                db.Database.IsNpgsql() ? IsolationLevel.ReadCommitted : IsolationLevel.Serializable, cancellation);
            if (db.Database.IsNpgsql())
            {
                var lockKey = BinaryPrimitives.ReadInt64BigEndian(SHA256.HashData(Encoding.UTF8.GetBytes(ProductCommercialLicense.Issuer+"\n"+authority.EnrollmentId)));
                await db.Database.ExecuteSqlInterpolatedAsync($"SELECT pg_advisory_xact_lock({lockKey})", cancellation);
            }
            var bindings = db.WorkspaceBindings.IgnoreQueryFilters().AsNoTracking();
            var existing = await bindings.SingleOrDefaultAsync(x => x.Issuer == ProductCommercialLicense.Issuer
                && x.Subject == authority.Subject && x.IdempotencyHash == keyHash, cancellation);
            if (existing is not null)
            {
                if (existing.RequestHash != requestHash) return new(WorkspaceCreateStatus.Conflict);
                if (!Current() || !license.AllowsWorkspace(existing.Slot)) return new(WorkspaceCreateStatus.Denied);
                return new(WorkspaceCreateStatus.Existing, existing.LegalEntityId, existing.Id);
            }
            var occupied = (await bindings.Where(x => x.Issuer == ProductCommercialLicense.Issuer
                    && x.EnrollmentId == authority.EnrollmentId).Select(x => x.Slot).ToListAsync(cancellation)).ToHashSet();
            var slot = Enumerable.Range(1, license.WorkspaceLimit).FirstOrDefault(x => !occupied.Contains(x));
            if (slot == 0) return new(WorkspaceCreateStatus.CapacityExhausted);
            if (!Current() || !license.AllowsWorkspace(slot)) return new(WorkspaceCreateStatus.Denied);
            var actor = ProductCommercialLicense.Issuer+"#"+authority.Subject;
            var company = new LegalEntity { TenantId = tenant, Code = "MAIN", RegisteredName = name, IsDefault = true,
                CountryCode = preferences.CountryCode, Currency = preferences.Currency, TimeZoneId = preferences.TimeZoneId, CreatedBy = actor };
            var owner = LocalUser.Federated("Workspace owner");
            owner.TenantId = tenant; owner.CreatedBy = actor;
            var binding = new CoreWorkspaceBinding { Issuer = ProductCommercialLicense.Issuer, Subject = authority.Subject,
                ClientId = authority.ClientId, CustomerId = authority.CustomerId, EnrollmentId = authority.EnrollmentId,
                Slot = slot, PurchasedLimit = license.WorkspaceLimit, LegalEntityId = company.Id, OwnerLocalUserId = owner.Id,
                IdempotencyHash = keyHash, RequestHash = requestHash, AuthorityUntil = authority.ExpiresAt,
                LicenseUntil = license.ExpiresAt, CreatedBy = actor };
            db.LegalEntities.Add(company);
            db.WorkLocations.Add(new WorkLocation { Code = "HQ", Name = "Head office", Type = "headquarters", LegalEntityId = company.Id, CreatedBy = actor });
            db.LocalUsers.Add(owner);
            // Composite principal keys must carry the trusted scope before tracking.
            var membership = new CoreCompanyMembership { TenantId = tenant, LegalEntityId = company.Id, LocalUserId = owner.Id,
                Role = CoreCompanyRoles.Owner, CreatedBy = actor };
            db.CompanyMemberships.Add(membership);
            db.ExternalIdentityLinks.Add(new ExternalIdentityLink { TenantId = tenant, Issuer = ProductCommercialLicense.Issuer,
                Subject = authority.Subject, LocalUserId = owner.Id, CreatedBy = actor });
            db.WorkspaceBindings.Add(binding);
            var evidence = JsonSerializer.Serialize(new { binding.Id, company_id = company.Id, owner_id = owner.Id,
                company_membership_id = membership.Id,
                enrollment_id = authority.EnrollmentId, slot, workspace_limit = license.WorkspaceLimit,
                authority_until = authority.ExpiresAt, license_until = license.ExpiresAt, operational_access_granted = false });
            db.AuditEntries.Add(new AuditEntry { EntityType = "CoreWorkspaceBinding", EntityId = binding.Id.ToString(),
                Action = "core.workspace.created", ActorSubjectId = actor, AfterJson = evidence, CorrelationId = keyHash, CreatedBy = actor });
            db.OutboxMessages.Add(new OutboxMessage { PublicId = binding.Id.ToString("D"), EventType = "core.workspace.created.v1",
                SubjectId = company.Id.ToString("D"), CorrelationId = keyHash, PayloadJson = evidence, CreatedBy = actor,
                AvailableAt = clock.GetUtcNow() });
            await db.SaveChangesAsync(cancellation);
            if (!Current()) return new(WorkspaceCreateStatus.Denied); // disposal rolls back all writes
            await transaction.CommitAsync(cancellation);
            return new(WorkspaceCreateStatus.Created, company.Id, binding.Id);
        }
        catch (Exception error) when (error is DbUpdateException or NpgsqlException)
        { return new(WorkspaceCreateStatus.Unavailable); } // caller obtains fresh proofs before retry
    }

    private static string Hash(string value) => Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(value)));
}

internal static class CoreWorkspaceProvisioningRegistration
{
    internal static IServiceCollection AddCoreWorkspaceProvisioning(this IServiceCollection services, IConfiguration config, string? reviewedConnection = null)
    {
        if (!config.GetValue<bool>("ERP:WorkspaceProvisioning:Enabled")) return services;
        if (!ProductIdentity.Enabled(config) || !config.GetValue<bool>("ERP:ProductLicensing:Enabled")
            || !config.GetValue<bool>("ERP:WorkspaceSetup:Enabled"))
            throw new InvalidOperationException("Workspace provisioning requires product identity, licensing and setup authority.");
        var connection = reviewedConnection ?? config.GetConnectionString("Hrm");
        try
        {
            if (string.IsNullOrWhiteSpace(connection) || string.IsNullOrWhiteSpace(new NpgsqlConnectionStringBuilder(connection).Database))
                throw new ArgumentException();
        }
        catch (ArgumentException) { throw new InvalidOperationException("Workspace provisioning requires a configured Core database."); }
        var options = new DbContextOptionsBuilder<HrmDbContext>().UseNpgsql(connection,
            pg => pg.MigrationsHistoryTable("__hrm_migrations", "hrm")).Options;
        services.AddSingleton(new CoreWorkspaceProvisioner(tenant => new HrmDbContext(options, new ProvisioningTenant(tenant)), TimeProvider.System));
        return services;
    }

    private sealed class ProvisioningTenant(string tenant) : ITenantAccessor { public string GetTenantId() => tenant; }
}
